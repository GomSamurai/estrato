export function rollInitialContracts(excludeIds: string[] = []): ActiveContractState[] {
  const avail = CONTRACT_POOL.filter((c) => !excludeIds.includes(c.id));
  const src = avail.length >= 3 ? avail : CONTRACT_POOL;
  const picked: ContractDef[] = [];
  const used = new Set<string>();
  let idx = Math.floor(Math.random() * src.length);
  while (picked.length < 3 && used.size < src.length) {
    const item = src[idx % src.length];
    if (!used.has(item.id)) {
      used.add(item.id);
      picked.push(item);
    }
    idx += 3;
  }
  return picked.map((c) => ({
    id: c.id,
    progress: 0,
    completed: false,
    claimed: false,
  }));
}

